def resolve_instance(registry: dict, needle: str) -> Tuple[str, dict]:
    """Exact name first, then a unique prefix. NetError 5 when unknown or ambiguous."""
    instances: Dict[str, dict] = registry["instances"]
    names = list(instances)
    low = needle.lower()

    exact = [n for n in names if n.lower() == low]
    if exact:
        return exact[0], instances[exact[0]]

    prefix = [n for n in names if n.lower().startswith(low)]
    if len(prefix) == 1:
        return prefix[0], instances[prefix[0]]
    if len(prefix) > 1:
        raise NetError(
            E_UNKNOWN_INSTANCE,
            f"ambiguous name `{needle}`: matches {', '.join(sorted(prefix))}. Use the full name.")
    known = ", ".join(sorted(names)) if names else "none"
    raise NetError(E_UNKNOWN_INSTANCE, f"unknown instance: `{needle}`. In the registry: {known}.")


def is_instance_dir(path: Path) -> bool:
    """The signature of a working Maestro instance: preferences.md plus bin/mem."""
    return (path / "private" / "preferences.md").is_file() and (path / "bin" / "mem").is_file()


def real(p: str) -> str:
    try:
        return os.path.realpath(Path(p).expanduser())
    except OSError:
        return p


def inside(path: str, root: str) -> bool:
    """`path` is `root` or sits under it (both already real)."""
    return path == root or path.startswith(root.rstrip(os.sep) + os.sep)


def overlaps(a: str, b: str) -> bool:
    """Two real paths coincide or one contains the other."""
    a_ = a.rstrip(os.sep) + os.sep
    b_ = b.rstrip(os.sep) + os.sep
    return a_.startswith(b_) or b_.startswith(a_)


# --------------------------------------------------------------------------
# Rendering and line surgery
# --------------------------------------------------------------------------

def yaml_path(path: str, what: str = "path") -> str:
    """A path as a YAML scalar: quoted when it holds a character the parser would misread."""
    if '"' in path:
        raise NetError(E_USAGE, f"{what} with double quotes can't be represented: {path}")
    return f'"{path}"' if re.search(r"[\s:#\[\]{}]", path) else path


def render_entry(name: str, path: str, domain: str, accepts: List[str]) -> str:
    """One instance block, same indentation and field order as render_registry."""
    lines = [
        f"  {name}:",
        f"    path: {yaml_path(path)}",
        f'    domain: "{domain}"',
        f"    accepts: [{', '.join(accepts)}]",
    ]
    return "\n".join(lines) + "\n"


def render_satellite(scope: str, repo: str, mother: str) -> str:
    return f"  {scope}:\n    repo: {yaml_path(repo, 'repo')}\n    mother: {mother}\n"


def render_registry(instances: List[dict], accepts: List[str]) -> str:
    lines = [REGISTRY_HEADER.rstrip("\n"), "version: 1", "instances:"]
    if not instances:
        lines.append("  # no instance found")
    for entry in instances:
        lines.append(f"  {entry['name']}:")
        lines.append(f"    path: {yaml_path(entry['path'])}")
        lines.append('    domain: ""')
        lines.append(f"    accepts: [{', '.join(accepts)}]")
    return "\n".join(lines) + "\n"


def _line_indent(line: str) -> Optional[int]:
    """Indentation of a content line; None for a blank line or a comment.

    Blank lines and comments are transparent to the block boundaries: they
    neither open nor close a block, so a comment among the instances breaks
    neither `instances:` nor a single entry.
    """
    stripped = line.rstrip("\n")
    if not stripped.strip() or stripped.lstrip().startswith("#"):
        return None
    return len(stripped) - len(stripped.lstrip(" "))


def _block_end(lines: List[str], start: int, boundary_indent: int) -> int:
    """End of the block starting at `start`: the first content line indented
    <= boundary_indent, or the start of the run of blank/comment lines right
    before it. That run belongs to what follows, so a comment between two
    entries survives the removal of the first. A run with nothing after it
    (end of file) stays inside the block, so an entry appended at the end of
    the file lands after it.
    """
    pending: Optional[int] = None
    for i in range(start, len(lines)):
        indent = _line_indent(lines[i])
        if indent is None:
            if pending is None:
                pending = i
            continue
        if indent > boundary_indent:
            pending = None
            continue
        return pending if pending is not None else i
    return len(lines)


def _block_header_index(lines: List[str], block: str) -> Optional[int]:
    for i, line in enumerate(lines):
        if _line_indent(line) == 0 and line.strip().split(":", 1)[0].strip() == block:
            return i
    return None


def insert_entry(text: str, entry_text: str, block: str = "instances") -> str:
    """Append entry_text at the end of the `<block>:` block, creating the block at the end when missing."""
    lines = text.splitlines(keepends=True)
    header = _block_header_index(lines, block)
    if header is None:
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        return "".join(lines) + f"{block}:\n" + entry_text
    insert_at = _block_end(lines, header + 1, 0)
    if insert_at == len(lines) and lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    return "".join(lines[:insert_at]) + entry_text + "".join(lines[insert_at:])


def remove_entry(text: str, name: str, block: str = "instances") -> str:
    """Drop the entry `name` from the `<block>:` block. Everything else stays."""
    lines = text.splitlines(keepends=True)
    header = _block_header_index(lines, block)
    if header is None:
        raise RegistryError(f"block `{block}` not found")
    block_end = _block_end(lines, header + 1, 0)
    for i in range(header + 1, block_end):
        line = lines[i]
        if _line_indent(line) == 2 and line.strip().split(":", 1)[0].strip() == name:
            end = _block_end(lines, i + 1, 2)
            return "".join(lines[:i]) + "".join(lines[end:])
    raise RegistryError(f"entry `{name}` not found in `{block}`")
