"""The machine registry of Maestro instances and satellites.

One file, `~/.claude/maestro-instances.yaml`, read by `maestro-net` and by the
plugin's SessionStart hook. Its schema is closed and flat (two blocks, two
levels), so a dedicated parser costs less than a YAML dependency and can
report line numbers. Anything outside the schema is an error, never a silent
degradation: a registry the parser doesn't understand must never read as an
empty registry.

`register`, `unregister` and `satellite add/remove` edit the file line by
line, so the owner's comments and the hand-filled `domain` and `accepts` of
the other entries survive byte for byte. Every write goes through
`write_registry`, which replaces the file atomically.

Exit codes are the channel's degradation contract, shared with `maestro-net`.
"""

from __future__ import annotations

import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

OK = 0
E_USAGE = 2
E_NO_REGISTRY = 3
E_BAD_REGISTRY = 4
E_UNKNOWN_INSTANCE = 5
E_VERB_REFUSED = 6
E_DEAD_PATH = 7
E_REMOTE_FAILED = 8
E_EXISTS = 9

VERBS = ("recap", "ask", "request")
DEFAULT_ACCEPTS = ("recap", "ask")
SUPPORTED_VERSIONS = (1,)
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
DEFAULT_REGISTRY = Path.home() / ".claude" / "maestro-instances.yaml"

REGISTRY_HEADER = (
    "# maestro-net: registry of the Maestro instances on this machine.\n"
    "# Generated by `maestro-net scan`. Two fields are the owner's to fill:\n"
    "#   domain  - what the instance is for, used for routing when the\n"
    "#             recipient isn't named explicitly.\n"
    f"#   accepts - the verbs the instance admits, among: {', '.join(VERBS)}.\n"
)


class RegistryError(Exception):
    """The registry text doesn't match the schema."""


class NetError(Exception):
    """A failure with an exit code; the message goes to stderr."""

    def __init__(self, code: int, message: str):
        super().__init__(message)
        self.code = code


# --------------------------------------------------------------------------
# Parsing
# --------------------------------------------------------------------------

def _scalar(raw: str, lineno: int, source: str):
    """A value: flow list, integer, or string (optionally quoted)."""
    v = raw.strip()
    if v.startswith("["):
        if not v.endswith("]"):
            raise RegistryError(f"{source}:{lineno}: unclosed list: {v}")
        inner = v[1:-1].strip()
        if not inner:
            return []
        return [_scalar(item, lineno, source) for item in inner.split(",")]
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v


def parse_registry(text: str, source: str) -> dict:
    """Read the registry. Raises RegistryError on any deviation from the schema."""
    data: Dict[str, object] = {}
    blocks: Dict[str, Dict[str, dict]] = {"instances": {}, "satellites": {}}
    current: Optional[str] = None
    block: Optional[str] = None
    seen_instances = False

    for lineno, line in enumerate(text.splitlines(), start=1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if "\t" in line[: len(line) - len(line.lstrip())]:
            raise RegistryError(f"{source}:{lineno}: tab indentation, spaces are required")

        indent = len(line) - len(line.lstrip(" "))
        body = line.strip()
        if ":" not in body:
            raise RegistryError(f"{source}:{lineno}: line without `key: value`: {body}")
        key, _, raw = body.partition(":")
        key = key.strip()
        raw = raw.strip()

        if indent == 0:
            block = key if key in blocks else None
            current = None
            if block is not None:
                if key == "instances":
                    seen_instances = True
                if raw:
                    raise RegistryError(
                        f"{source}:{lineno}: `{key}:` takes no value on the same line")
                continue
            if key not in ("version",):
                raise RegistryError(f"{source}:{lineno}: unknown top-level key: {key}")
            data[key] = _scalar(raw, lineno, source)
        elif indent == 2:
            if block is None:
                raise RegistryError(
                    f"{source}:{lineno}: indented block outside `instances:` or `satellites:`")
            if raw:
                raise RegistryError(
                    f"{source}:{lineno}: the name `{key}` takes no value on the same line")
            if key in blocks[block]:
                raise RegistryError(f"{source}:{lineno}: duplicate entry in `{block}`: {key}")
            current = key
            blocks[block][key] = {}
        elif indent == 4:
            if current is None or block is None:
                raise RegistryError(f"{source}:{lineno}: field `{key}` outside an entry")
            blocks[block][current][key] = _scalar(raw, lineno, source)
        else:
            raise RegistryError(
                f"{source}:{lineno}: indentation of {indent} spaces, expected 0, 2 or 4")

    if not seen_instances:
        raise RegistryError(f"{source}: missing `instances` key")
    data["instances"] = blocks["instances"]
    data["satellites"] = blocks["satellites"]
    _validate(data, source)
    return data


def _validate(data: dict, source: str) -> None:
    if "version" not in data:
        raise RegistryError(f"{source}: missing `version` key")
    if data["version"] not in SUPPORTED_VERSIONS:
        raise RegistryError(
            f"{source}: version {data['version']} not supported "
            f"(this build reads: {', '.join(str(v) for v in SUPPORTED_VERSIONS)})")
    if not isinstance(data.get("instances"), dict):
        raise RegistryError(f"{source}: `instances` is not a block of instances")

    for name, entry in data["instances"].items():
        path = entry.get("path")
        if not path or not isinstance(path, str):
            raise RegistryError(f"{source}: instance `{name}` has no `path` field")
        accepts = entry.get("accepts")
        if accepts is None:
            continue
        if not isinstance(accepts, list):
            raise RegistryError(f"{source}: `accepts` of `{name}` is not a list")
        kept = []
        for verb in accepts:
            if verb not in VERBS:
                print(f"maestro-net: `{name}` declares the unknown verb `{verb}` in `accepts` "
                      f"(known: {', '.join(VERBS)}), ignored.", file=sys.stderr)
                continue
            kept.append(verb)
        entry["accepts"] = kept

    for scope, entry in data.get("satellites", {}).items():
        # The scope reaches a shell `export` line at session start: only a slug.
        if not NAME_RE.fullmatch(str(scope)):
            raise RegistryError(f"{source}: satellite `{scope}` is not a slug (a-z, 0-9, `-`)")
        for field in ("repo", "mother"):
            if not entry.get(field) or not isinstance(entry.get(field), str):
                raise RegistryError(f"{source}: satellite `{scope}` has no `{field}` field")


# --------------------------------------------------------------------------
# Loading and writing
# --------------------------------------------------------------------------

def registry_path(arg: Optional[str] = None) -> Path:
    """`--registry`, else env MAESTRO_INSTANCES, else the default."""
    if arg:
        return Path(arg).expanduser()
    env = os.environ.get("MAESTRO_INSTANCES")
    if env:
        return Path(env).expanduser()
    return DEFAULT_REGISTRY


def missing_registry(path: Path) -> NetError:
    return NetError(E_NO_REGISTRY, f"no registry at {path}\nCreate it with: maestro-net scan --write")


def load_registry_text(path: Path) -> Tuple[str, dict]:
    """Raw text plus validated data. NetError 3 when the file is missing or unreadable, 4 when malformed."""
    if not path.is_file():
        raise missing_registry(path)
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise NetError(E_NO_REGISTRY, f"unreadable registry: {path}: {exc}")
    try:
        return text, parse_registry(text, str(path))
    except RegistryError as exc:
        raise NetError(E_BAD_REGISTRY, f"malformed registry: {exc}")


def load_registry(arg: Optional[str] = None) -> Tuple[dict, Path]:
    path = registry_path(arg)
    _, data = load_registry_text(path)
    return data, path


def load_or_empty(path: Path) -> Tuple[str, dict]:
    """Like load_registry_text, with an empty in-memory registry when the file doesn't exist."""
    if not path.is_file():
        return "version: 1\ninstances:\n", {"version": 1, "instances": {}, "satellites": {}}
    return load_registry_text(path)


def write_registry(path: Path, text: str) -> None:
    """Replace the registry atomically: every session start reads this file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".maestro-instances.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


